CREATE UNIQUE INDEX IF NOT EXISTS orders_paytm_order_key
  ON public.orders(paytm_order_id) WHERE paytm_order_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS orders_paytm_txn_key
  ON public.orders(paytm_transaction_id) WHERE paytm_transaction_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.payment_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
  payment_provider text NOT NULL CHECK (payment_provider IN ('PAYTM')),
  gateway_order_id text NOT NULL,
  gateway_transaction_id text,
  amount numeric(12,2) NOT NULL CHECK (amount > 0),
  status text NOT NULL DEFAULT 'initiating'
    CHECK (status IN ('initiating', 'pending', 'failed', 'success', 'duplicate_paid', 'unknown')),
  result_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS payment_attempts_provider_order_key
  ON public.payment_attempts(payment_provider, gateway_order_id);
CREATE UNIQUE INDEX IF NOT EXISTS payment_attempts_provider_txn_key
  ON public.payment_attempts(payment_provider, gateway_transaction_id)
  WHERE gateway_transaction_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS payment_attempts_order_created_idx
  ON public.payment_attempts(order_id, created_at DESC);

