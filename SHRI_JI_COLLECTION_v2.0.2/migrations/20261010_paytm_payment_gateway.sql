-- Atomically associates one unique Paytm payment attempt with an existing ONLINE order.
CREATE OR REPLACE FUNCTION public.begin_paytm_attempt(
  p_order_id bigint, p_user uuid, p_gateway_order_id text, p_amount numeric
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_o public.orders;
  v_a public.payment_attempts;
BEGIN
  SELECT * INTO v_o FROM public.orders
  WHERE id = p_order_id AND user_id = p_user
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
  IF v_o.payment_status = 'paid' THEN RAISE EXCEPTION 'PAYMENT_COMPLETE'; END IF;
  IF v_o.payment_method <> 'ONLINE' OR v_o.order_status <> 'pending'
     OR v_o.payment_status NOT IN ('pending', 'failed') THEN
    RAISE EXCEPTION 'ORDER_NOT_PAYABLE';
  END IF;
  IF p_amount IS NULL OR round(v_o.total * 100) <> round(p_amount * 100) THEN
    RAISE EXCEPTION 'AMOUNT_MISMATCH';
  END IF;
  IF p_gateway_order_id IS NULL OR length(p_gateway_order_id) < 8 OR length(p_gateway_order_id) > 50 THEN
    RAISE EXCEPTION 'INVALID_GATEWAY_ORDER_ID';
  END IF;

  INSERT INTO public.payment_attempts(order_id, payment_provider, gateway_order_id, amount, status)
  VALUES (v_o.id, 'PAYTM', p_gateway_order_id, v_o.total, 'initiating')
  RETURNING * INTO v_a;

  UPDATE public.orders SET payment_provider = 'PAYTM', paytm_order_id = p_gateway_order_id, updated_at = now()
  WHERE id = v_o.id RETURNING * INTO v_o;
  RETURN jsonb_build_object('attempt', to_jsonb(v_a), 'order', to_jsonb(v_o));
END $$;

-- Reconcile only a result obtained from Paytm's authenticated Transaction Status API.
-- A failed/pending callback can never overwrite a paid order. Repeated success is idempotent.
CREATE OR REPLACE FUNCTION public.reconcile_paytm_payment(
  p_gateway_order_id text,
  p_transaction_id text,
  p_amount numeric,
  p_txn_status text,
  p_result_code text DEFAULT NULL
) RETURNS public.orders
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_a public.payment_attempts;
  v_o public.orders;
  v_status text := upper(coalesce(p_txn_status, 'PENDING'));
BEGIN
  SELECT * INTO v_a FROM public.payment_attempts
  WHERE payment_provider = 'PAYTM' AND gateway_order_id = p_gateway_order_id
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;

  SELECT * INTO v_o FROM public.orders WHERE id = v_a.order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
  IF p_amount IS NULL OR round(p_amount * 100) <> round(v_a.amount * 100)
     OR round(p_amount * 100) <> round(v_o.total * 100) THEN
    RAISE EXCEPTION 'AMOUNT_MISMATCH';
  END IF;
  IF v_status NOT IN ('TXN_SUCCESS', 'TXN_FAILURE', 'PENDING') THEN v_status := 'PENDING'; END IF;

  IF v_status = 'TXN_SUCCESS' THEN
    IF p_transaction_id IS NULL OR btrim(p_transaction_id) = '' THEN
      RAISE EXCEPTION 'MISSING_TRANSACTION_ID';
    END IF;
    IF v_o.payment_status = 'paid' THEN
      IF v_o.payment_provider = 'PAYTM' AND v_o.paytm_transaction_id = p_transaction_id THEN
        UPDATE public.payment_attempts SET status = 'success', gateway_transaction_id = p_transaction_id,
          result_code = p_result_code, updated_at = now(), completed_at = coalesce(completed_at, now())
        WHERE id = v_a.id;
      ELSE
        UPDATE public.payment_attempts SET status = 'duplicate_paid', gateway_transaction_id = p_transaction_id,
          result_code = p_result_code, updated_at = now(), completed_at = coalesce(completed_at, now())
        WHERE id = v_a.id;
        UPDATE public.orders SET admin_note = trim(coalesce(admin_note || ' | ', '') ||
          'DUPLICATE PAYMENT SUCCESS: Paytm txn ' || p_transaction_id || ' needs manual reconciliation/refund'),
          updated_at = now()
        WHERE id = v_o.id RETURNING * INTO v_o;
      END IF;
      RETURN v_o;
    END IF;

    UPDATE public.payment_attempts SET status = 'success', gateway_transaction_id = p_transaction_id,
      result_code = p_result_code, updated_at = now(), completed_at = coalesce(completed_at, now())
    WHERE id = v_a.id;
    UPDATE public.orders SET payment_status = 'paid', payment_provider = 'PAYTM',
      paytm_order_id = p_gateway_order_id, paytm_transaction_id = p_transaction_id,
      paid_at = coalesce(paid_at, now()), updated_at = now(),
      order_status = CASE WHEN order_status = 'pending' THEN 'confirmed' ELSE order_status END,
      admin_note = CASE WHEN order_status = 'cancelled'
        THEN trim(coalesce(admin_note || ' | ', '') || 'PAYTM PAYMENT SUCCESS AFTER CANCELLATION - review refund/reinstatement')
        ELSE admin_note END
    WHERE id = v_o.id RETURNING * INTO v_o;
    RETURN v_o;
  ELSIF v_status = 'TXN_FAILURE' THEN
    UPDATE public.payment_attempts SET status = 'failed', result_code = p_result_code,
      updated_at = now(), completed_at = coalesce(completed_at, now())
    WHERE id = v_a.id AND status <> 'success';
    UPDATE public.orders SET payment_status = CASE WHEN payment_status = 'pending' THEN 'failed' ELSE payment_status END,
      updated_at = now()
    WHERE id = v_o.id AND payment_status <> 'paid' AND payment_status <> 'cancelled'
    RETURNING * INTO v_o;
    RETURN v_o;
  ELSE
    UPDATE public.payment_attempts SET status = 'pending', result_code = p_result_code, updated_at = now()
    WHERE id = v_a.id AND status NOT IN ('success', 'duplicate_paid');
    UPDATE public.orders SET payment_status = CASE WHEN payment_status = 'failed' THEN 'pending' ELSE payment_status END,
      updated_at = now()
    WHERE id = v_o.id AND order_status = 'pending' AND payment_status <> 'paid'
    RETURNING * INTO v_o;
    RETURN v_o;
  END IF;
END $$;

-- Razorpay continues to call the same RPC signature. Mark its provider explicitly when paid.
CREATE OR REPLACE FUNCTION public.mark_order_paid(
  p_razorpay_order_id text, p_payment_id text, p_amount_paise bigint DEFAULT NULL
) RETURNS public.orders
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_o public.orders;
BEGIN
  SELECT * INTO v_o FROM public.orders WHERE razorpay_order_id = p_razorpay_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
  IF p_amount_paise IS NOT NULL AND p_amount_paise <> round(v_o.total * 100) THEN
    RAISE EXCEPTION 'AMOUNT_MISMATCH';
  END IF;
  IF v_o.payment_status = 'paid' THEN
    IF v_o.payment_provider = 'RAZORPAY' AND v_o.razorpay_payment_id = p_payment_id THEN
      RETURN v_o;
    END IF;
    UPDATE public.orders SET admin_note = trim(coalesce(admin_note || ' | ', '') ||
      'DUPLICATE RAZORPAY PAYMENT SUCCESS: txn ' || coalesce(p_payment_id, 'unknown') || ' needs manual reconciliation/refund'),
      updated_at = now()
    WHERE id = v_o.id RETURNING * INTO v_o;
    RETURN v_o;
  END IF;
  UPDATE public.orders SET
    payment_status = 'paid', payment_provider = 'RAZORPAY', razorpay_payment_id = p_payment_id,
    paid_at = coalesce(paid_at, now()), updated_at = now(),
    order_status = CASE WHEN order_status = 'pending' THEN 'confirmed' ELSE order_status END,
    admin_note = CASE WHEN order_status = 'cancelled'
      THEN trim(coalesce(admin_note || ' | ', '') || 'PAID AFTER CANCELLATION - refund or reinstate manually')
      ELSE admin_note END
  WHERE id = v_o.id RETURNING * INTO v_o;
  RETURN v_o;
END $$;

