-- Replacements keep the original function signatures so the existing API can keep calling them.
create or replace function public.create_order(
  p_user uuid, p_customer jsonb, p_items jsonb, p_method text, p_key text,
  p_shipping_flat numeric default 0, p_free_above numeric default null
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_existing public.orders; v_need record; v_item jsonb; v_prod public.products;
  v_variant jsonb; v_variant_id text; v_new_variants jsonb; v_new_stock integer;
  v_qty int; v_need_stock int; v_size text; v_pack int; v_min int;
  v_unit numeric; v_regular numeric; v_sale numeric;
  v_lines jsonb := '[]'::jsonb; v_sub numeric := 0; v_ship numeric := 0;
  v_order public.orders; v_number text; v_label text; v_attrs jsonb; v_line_idx int := 0;
begin
  if p_user is null then raise exception 'LOGIN_REQUIRED'; end if;
  if p_method not in ('COD','ONLINE') then raise exception 'INVALID_METHOD'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 20 then
    raise exception 'INVALID_ITEMS';
  end if;
  if p_key is not null then
    select * into v_existing from public.orders where user_id = p_user and idempotency_key = p_key;
    if found then return jsonb_build_object('existing', true, 'order', to_jsonb(v_existing)); end if;
  end if;

  -- Lock each product row. Group by product and chosen variant so repeated cart lines cannot bypass stock checks.
  for v_need in
    select (e->>'productId')::bigint as pid, nullif(e->>'variantId','') as variant_id, sum((e->>'qty')::int)::int as qty
    from jsonb_array_elements(p_items) as t(e) group by 1,2 order by 1,2
  loop
    select * into v_prod from public.products where id = v_need.pid for update;
    if not found or not v_prod.active or v_prod.archived_at is not null then raise exception 'UNAVAILABLE'; end if;
    if jsonb_array_length(coalesce(v_prod.variants, '[]'::jsonb)) > 0 then
      if v_need.variant_id is null then raise exception 'VARIANT_REQUIRED:%', v_prod.name; end if;
      select x.value into v_variant from jsonb_array_elements(v_prod.variants) as x(value) where x.value->>'id' = v_need.variant_id;
      if v_variant is null or coalesce((v_variant->>'active')::boolean, true) = false then raise exception 'INVALID_VARIANT:%', v_prod.name; end if;
      v_pack := greatest(1, coalesce((v_variant->>'pack_quantity')::int, 1));
      v_min := greatest(1, coalesce((v_variant->>'min_order_qty')::int, v_prod.min_order_qty, 1));
      if coalesce((v_variant->>'stock')::int, 0) < v_need.qty * v_pack then raise exception 'OUT_OF_STOCK:%', v_prod.name; end if;
    else
      if v_need.variant_id is not null then raise exception 'INVALID_VARIANT:%', v_prod.name; end if;
      v_pack := greatest(1, coalesce(v_prod.pack_size, 1));
      v_min := greatest(1, coalesce(v_prod.min_order_qty, 1));
      if v_prod.stock < v_need.qty * v_pack then raise exception 'OUT_OF_STOCK:%', v_prod.name; end if;
    end if;
  end loop;

  for v_item in select e.value from jsonb_array_elements(p_items) with ordinality e(value, ord) order by e.ord loop
    v_line_idx := v_line_idx + 1;
    select * into v_prod from public.products where id = (v_item->>'productId')::bigint for update;
    v_qty := (v_item->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 100 then raise exception 'INVALID_ITEMS'; end if;
    v_variant_id := nullif(v_item->>'variantId','');
    v_size := nullif(trim(coalesce(v_item->>'size','')), '');
    if jsonb_array_length(coalesce(v_prod.variants, '[]'::jsonb)) > 0 then
      select x.value into v_variant from jsonb_array_elements(v_prod.variants) as x(value) where x.value->>'id' = v_variant_id;
      if v_variant is null or coalesce((v_variant->>'active')::boolean, true) = false then raise exception 'INVALID_VARIANT:%', v_prod.name; end if;
      v_pack := greatest(1, coalesce((v_variant->>'pack_quantity')::int, 1));
      v_min := greatest(1, coalesce((v_variant->>'min_order_qty')::int, v_prod.min_order_qty, 1));
      if v_qty < v_min then raise exception 'MIN_QTY:%:%', v_prod.name, v_min; end if;
      v_regular := (v_variant->>'price')::numeric;
      v_sale := nullif(v_variant->>'sale_price','')::numeric;
      v_unit := case when v_sale is not null and v_sale > 0 and v_sale < v_regular then v_sale else v_regular end;
      v_label := coalesce(nullif(v_variant->>'label',''), v_prod.name);
      v_attrs := coalesce(v_variant->'attributes', '{}'::jsonb);
      v_need_stock := v_qty * v_pack;
      select jsonb_agg(case when x.value->>'id' = v_variant_id then jsonb_set(x.value, '{stock}', to_jsonb(greatest(0, coalesce((x.value->>'stock')::int,0)-v_need_stock)), true) else x.value end order by x.ord),
             sum(case when x.value->>'id' = v_variant_id then greatest(0, coalesce((x.value->>'stock')::int,0)-v_need_stock) else coalesce((x.value->>'stock')::int,0) end)::int
        into v_new_variants, v_new_stock
        from jsonb_array_elements(v_prod.variants) with ordinality x(value, ord);
      update public.products set variants = v_new_variants, stock = coalesce(v_new_stock,0) where id = v_prod.id;
    else
      if coalesce(array_length(v_prod.sizes, 1), 0) > 0 then
        if v_size is null or not (v_size = any (v_prod.sizes)) then raise exception 'SIZE_REQUIRED:%', v_prod.name; end if;
      else v_size := null; end if;
      v_pack := greatest(1, coalesce(v_prod.pack_size, 1));
      v_min := greatest(1, coalesce(v_prod.min_order_qty, 1));
      if v_qty < v_min then raise exception 'MIN_QTY:%:%', v_prod.name, v_min; end if;
      v_unit := case when v_prod.sale_price is not null and v_prod.sale_price > 0 and v_prod.sale_price < v_prod.price then v_prod.sale_price else v_prod.price end;
      v_label := v_prod.name; v_attrs := '{}'::jsonb; v_need_stock := v_qty * v_pack;
      update public.products set stock = stock - v_need_stock where id = v_prod.id;
    end if;
    v_sub := v_sub + v_unit * v_qty;
    v_lines := v_lines || jsonb_build_object(
      'product_id', v_prod.id, 'name', v_prod.name, 'slug', v_prod.slug, 'size', v_size,
      'variant_id', v_variant_id, 'variant_label', case when v_variant_id is not null then v_label else null end,
      'variant_attributes', v_attrs, 'pack_quantity', v_pack, 'min_order_qty', v_min,
      'qty', v_qty, 'unit_price', v_unit, 'image', v_prod.image_urls[1], 'item_index', v_line_idx,
      'return_eligible', coalesce(v_prod.return_eligible, false), 'return_window_days', coalesce(v_prod.return_window_days, 0),
      'return_conditions', v_prod.return_conditions, 'return_instructions', v_prod.return_instructions, 'refund_policy', v_prod.refund_policy);
  end loop;

  -- Exact delivery policy: subtotal is post-discount merchandise amount, before delivery/tax/fees.
  v_ship := case when v_sub >= 1000 then 0 when v_sub >= 499 then 40 else 50 end;
  v_number := 'SJC-' || to_char(now() at time zone 'Asia/Kolkata', 'YYMMDD') || '-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 5));
  insert into public.orders(order_number, user_id, customer_name, phone, email, address, city, state, pincode,
                            payment_method, payment_status, order_status, items, subtotal, shipping, total, idempotency_key)
  values (v_number, p_user, p_customer->>'name', p_customer->>'phone', nullif(p_customer->>'email',''), p_customer->>'address',
          p_customer->>'city', p_customer->>'state', p_customer->>'pincode', p_method, 'pending', 'pending', v_lines, v_sub, v_ship, v_sub + v_ship, p_key)
  returning * into v_order;
  insert into public.order_events(order_id, order_number, event_type, old_status, new_status, actor_user_id, note)
  values (v_order.id, v_order.order_number, 'order_created', null, v_order.order_status, p_user, 'Order created');
  return jsonb_build_object('existing', false, 'order', to_jsonb(v_order));
end $$;

create or replace function public.restore_order_stock(p_order bigint) returns void
language plpgsql security definer set search_path = public as $$
declare v_o public.orders; v_i jsonb; v_prod public.products; v_vid text; v_pack int; v_count int; v_variants jsonb; v_stock int;
begin
  select * into v_o from public.orders where id = p_order for update;
  if not found or v_o.stock_restored then return; end if;
  for v_i in select value from jsonb_array_elements(v_o.items) loop
    v_vid := nullif(v_i->>'variant_id','');
    v_pack := greatest(1, coalesce((v_i->>'pack_quantity')::int, 1));
    v_count := greatest(0, coalesce((v_i->>'qty')::int, 0)) * v_pack;
    select * into v_prod from public.products where id = (v_i->>'product_id')::bigint for update;
    if not found then continue; end if;
    if v_vid is not null and jsonb_array_length(coalesce(v_prod.variants, '[]'::jsonb)) > 0 then
      select jsonb_agg(case when x.value->>'id' = v_vid then jsonb_set(x.value, '{stock}', to_jsonb(coalesce((x.value->>'stock')::int,0)+v_count), true) else x.value end order by x.ord),
             sum(case when x.value->>'id' = v_vid then coalesce((x.value->>'stock')::int,0)+v_count else coalesce((x.value->>'stock')::int,0) end)::int
        into v_variants, v_stock from jsonb_array_elements(v_prod.variants) with ordinality x(value,ord);
      update public.products set variants = v_variants, stock = coalesce(v_stock, stock + v_count) where id = v_prod.id;
    else
      update public.products set stock = stock + v_count where id = v_prod.id;
    end if;
  end loop;
  update public.orders set stock_restored = true where id = p_order;
end $$;

create or replace function public.set_order_status(p_order_number text, p_status text, p_user uuid default null)
returns public.orders language plpgsql security definer set search_path = public as $$
declare v_o public.orders; v_old text;
begin
  if p_status not in ('pending','confirmed','processing','packed','shipped','out_for_delivery','delivered','cancelled') then raise exception 'INVALID_STATUS'; end if;
  select * into v_o from public.orders where order_number = p_order_number for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if p_user is not null then
    if v_o.user_id is distinct from p_user then raise exception 'NOT_FOUND'; end if;
    if p_status <> 'cancelled' or v_o.order_status <> 'pending' or v_o.payment_status = 'paid' then raise exception 'NOT_ALLOWED'; end if;
  end if;
  if v_o.order_status = 'cancelled' and p_status <> 'cancelled' then raise exception 'CANCELLED_LOCKED'; end if;
  if v_o.order_status = p_status then return v_o; end if;
  if p_status in ('confirmed','processing','packed','shipped','out_for_delivery','delivered') and v_o.payment_method = 'ONLINE' and v_o.payment_status <> 'paid' then raise exception 'PAYMENT_PENDING'; end if;
  if p_status = 'processing' and v_o.order_status not in ('confirmed','processing') then raise exception 'INVALID_TRANSITION'; end if;
  if p_status = 'packed' and v_o.order_status not in ('confirmed','processing','packed') then raise exception 'INVALID_TRANSITION'; end if;
  if p_status = 'shipped' and v_o.order_status not in ('packed','shipped') then raise exception 'INVALID_TRANSITION'; end if;
  if p_status = 'out_for_delivery' and v_o.order_status not in ('shipped','out_for_delivery') then raise exception 'INVALID_TRANSITION'; end if;
  if p_status = 'delivered' and v_o.order_status not in ('shipped','out_for_delivery','delivered') then raise exception 'INVALID_TRANSITION'; end if;
  if p_status = 'confirmed' and v_o.order_status not in ('pending','confirmed') then raise exception 'INVALID_TRANSITION'; end if;
  if p_status = 'cancelled' and v_o.order_status in ('shipped','out_for_delivery','delivered') then raise exception 'CANCEL_NOT_ALLOWED'; end if;
  -- A captured online payment must be refunded through its gateway before cancellation can be finalized.
  if p_status = 'cancelled' and v_o.payment_method = 'ONLINE' and v_o.payment_status = 'paid' then raise exception 'REFUND_REQUIRED'; end if;
  v_old := v_o.order_status;
  if p_status = 'cancelled' then
    perform public.restore_order_stock(v_o.id);
    update public.orders set order_status = 'cancelled', updated_at = now(),
      payment_status = case when payment_status in ('pending','failed') and payment_method = 'ONLINE' then 'cancelled' else payment_status end
    where id = v_o.id returning * into v_o;
  else
    update public.orders set order_status = p_status, updated_at = now(), delivered_at = case when p_status='delivered' then coalesce(delivered_at, now()) else delivered_at end,
      payment_status = case when p_status = 'delivered' and payment_method = 'COD' and payment_status = 'pending' then 'paid' else payment_status end,
      paid_at = case when p_status = 'delivered' and payment_method = 'COD' and payment_status = 'pending' then now() else paid_at end
    where id = v_o.id returning * into v_o;
  end if;
  insert into public.order_events(order_id, order_number, event_type, old_status, new_status, actor_user_id, note)
  values (v_o.id, v_o.order_number, case when p_status='cancelled' then 'order_cancelled' else 'status_changed' end, v_old, v_o.order_status, p_user, null);
  return v_o;
end $$;

-- Record verified Razorpay payment transitions in the order timeline and never overwrite an earlier successful payment.
create or replace function public.mark_order_paid(p_razorpay_order_id text, p_payment_id text, p_amount_paise bigint default null)
returns public.orders language plpgsql security definer set search_path = public as $$
declare v_o public.orders; v_old text; v_payment_owner bigint;
begin
  if nullif(trim(p_payment_id), '') is null then raise exception 'INVALID_PAYMENT_ID'; end if;
  select * into v_o from public.orders where razorpay_order_id = p_razorpay_order_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if p_amount_paise is not null and p_amount_paise <> round(v_o.total * 100) then raise exception 'AMOUNT_MISMATCH'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_payment_id, 0));
  select id into v_payment_owner from public.orders where razorpay_payment_id = p_payment_id and id <> v_o.id limit 1;
  if found then raise exception 'PAYMENT_ALREADY_USED'; end if;
  if v_o.payment_status = 'paid' then
    if v_o.razorpay_payment_id = p_payment_id then return v_o; end if;
    raise exception 'ALREADY_PAID';
  end if;
  v_old := v_o.order_status;
  if v_o.order_status = 'cancelled' then
    update public.orders set payment_status = 'paid', razorpay_payment_id = p_payment_id, paid_at = now(), updated_at = now(),
      admin_note = trim(coalesce(admin_note || ' | ', '') || 'PAID AFTER CANCELLATION - reconcile/refund manually')
    where id = v_o.id returning * into v_o;
    insert into public.order_events(order_id, order_number, event_type, old_status, new_status, note)
    values (v_o.id, v_o.order_number, 'payment_received_after_cancellation', v_old, v_o.order_status, 'Razorpay reported a successful payment after cancellation; manual reconciliation is required.');
    return v_o;
  end if;
  update public.orders set payment_status = 'paid', razorpay_payment_id = p_payment_id, paid_at = now(), updated_at = now(),
    order_status = case when order_status = 'pending' then 'confirmed' else order_status end
  where id = v_o.id returning * into v_o;
  insert into public.order_events(order_id, order_number, event_type, old_status, new_status, note)
  values (v_o.id, v_o.order_number, 'payment_confirmed', v_old, v_o.order_status, 'Razorpay payment verified server-side.');
  return v_o;
end $$;

